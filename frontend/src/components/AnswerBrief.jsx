import React, { useState } from "react";
import AnswerText from "./AnswerText.jsx";

const STATUS = {
  answered: { label: "Grounded answer", note: "Every statement is backed by the cited evidence.", cls: "ok" },
  partial: { label: "Partly answered", note: "The knowledge base covers only part of this question.", cls: "partial" },
  insufficient: { label: "Not enough evidence", note: "The knowledge base does not support an answer to this question.", cls: "none" },
};

const MODE_TEXT = {
  llm: (g) => `Generated by ${g.model} from retrieved evidence only`,
  extractive: () => "Extractive mode: sentences quoted from evidence, no LLM configured",
  extractive_fallback: () => "LLM unavailable: showing quoted evidence instead",
  gate: () => "LLM not called: no passage passed the relevance threshold",
};

function ms(v) {
  return v >= 1000 ? `${(v / 1000).toFixed(1)} s` : `${Math.round(v)} ms`;
}

export default function AnswerBrief({ result, onCite }) {
  const [showTrace, setShowTrace] = useState(false);
  const g = result.generation;
  const extractive = g.mode?.startsWith("extractive");
  let s = STATUS[result.status] || STATUS.answered;
  if (extractive && result.status !== "insufficient") {
    s = {
      label: "Evidence excerpts",
      note: "No LLM is configured, so relevant sentences are quoted from the evidence. Read them as excerpts, not a complete answer.",
      cls: "partial",
    };
  }
  const r = result.retrieval;
  const t = result.timings_ms;
  const cited = result.used_evidence || [];

  return (
    <article className={`brief brief--${s.cls}`} aria-live="polite">
      <header className="brief__head">
        <span className={`status status--${s.cls}`}>{s.label}</span>
        <span className="brief__rag">RAG answer</span>
      </header>
      <p className="brief__note">{s.note}</p>

      <AnswerText text={result.answer} onCite={onCite} />

      {result.missing_information && result.status !== "insufficient" && (
        <p className="brief__missing">
          <strong>Not covered by the knowledge base:</strong> {result.missing_information}
        </p>
      )}
      {r.missing_entities?.length > 0 && !extractive && (
        <p className="brief__missing">
          <strong>Not found in any indexed document:</strong> {r.missing_entities.join(", ")}
        </p>
      )}

      <footer className="brief__foot">
        <p className="provenance">
          {(MODE_TEXT[g.mode] || MODE_TEXT.llm)(g)}.{" "}
          {cited.length > 0 ? (
            <>
              Cites{" "}
              {cited.map((id) => (
                <button key={id} type="button" className="cite" onClick={() => onCite(id)}>
                  {id}
                </button>
              ))}{" "}
              of {result.evidence.length} retrieved passages.
            </>
          ) : (
            <>No passage cited.</>
          )}
        </p>

        <ol className="pipeline" aria-label="Pipeline timing">
          <li>
            <span>Retrieval</span>
            <b>{ms(t.retrieval_total)}</b>
          </li>
          <li>
            <span>Generation</span>
            <b>{ms(t.generation)}</b>
          </li>
          <li>
            <span>Total</span>
            <b>{ms(t.total)}</b>
          </li>
        </ol>

        <button type="button" className="linkish" aria-expanded={showTrace} onClick={() => setShowTrace((v) => !v)}>
          {showTrace ? "Hide retrieval details" : "Show retrieval details"}
        </button>
        {showTrace && (
          <dl className="trace-details">
            <dt>Method</dt>
            <dd>{r.method}</dd>
            <dt>Vector query</dt>
            <dd>{r.dense_query}</dd>
            <dt>Keyword query</dt>
            <dd>{r.keyword_query || "(none)"}</dd>
            <dt>Best vector match</dt>
            <dd>
              cosine {r.best_dense_score.toFixed(3)} (threshold {r.min_dense_score.toFixed(2)})
            </dd>
            <dt>Candidates</dt>
            <dd>
              {r.candidates.dense} vector, {r.candidates.keyword} keyword, {r.candidates.fused} after fusion
            </dd>
            {r.missing_terms?.length > 0 && (
              <>
                <dt>Terms absent from corpus</dt>
                <dd>{r.missing_terms.join(", ")}</dd>
              </>
            )}
            <dt>Generator</dt>
            <dd>
              {g.provider} / {g.model} ({g.mode})
            </dd>
            {g.error && (
              <>
                <dt>Generator error</dt>
                <dd>{g.error}</dd>
              </>
            )}
            <dt>Query id</dt>
            <dd>{result.query_id}</dd>
          </dl>
        )}
      </footer>
    </article>
  );
}
